# ── 股票筛选规则 ──
def is_allowed_stock(code: str) -> bool:
    """检查股票代码是否在允许的交易范围内"""
    code = code.strip()
    if code.startswith("688"):
        return False  # 科创板
    if code.startswith("68") and len(code) >= 6:
        return False  # 其他68开头
    if code.startswith("8") and len(code) >= 6:
        return False  # 北证
    if not code.startswith(("6", "0", "3")):
        return False  # 只允许60/00/30开头
    return True


def validate_stock_pool(pool: dict) -> dict:
    """过滤股票池，剔除不允许的股票代码"""
    return {name: code for name, code in pool.items() if is_allowed_stock(code)}


